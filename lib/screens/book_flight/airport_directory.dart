  static List<AirportOption> search(String query, {String? excludeCode}) {
    // Normalize query by keeping only alphanumeric characters and
    // replacing other characters with spaces. This makes inputs like
    // "Los Angeles(LAX)" match the stored "Los Angeles (LAX)" label.
    final normalized = query
        .toLowerCase()
        .replaceAll(RegExp(r'[^a-z0-9]+'), ' ')
        .trim();
    final results = airports.where((airport) {
      if (excludeCode != null && airport.code == excludeCode) {
        return false;
      }
      if (normalized.isEmpty) {
        return true;
      }
      final haystack = [
        airport.code,
        airport.city,
        airport.name,
        airport.country,
        airport.shortLabel,
        airport.fullLabel,
      ].join(' ').toLowerCase();
      final haystackNormalized = haystack
          .replaceAll(RegExp(r'[^a-z0-9]+'), ' ')
          .trim();
      return haystackNormalized.contains(normalized);
    }).toList();

    results.sort((a, b) {
      final aCodeExact = a.code.toLowerCase() == normalized;
      final bCodeExact = b.code.toLowerCase() == normalized;
      if (aCodeExact != bCodeExact) {
        return aCodeExact ? -1 : 1;
      }
      final aStarts =
          a.code.toLowerCase().startsWith(normalized) ||
          a.city.toLowerCase().startsWith(normalized);
      final bStarts =
          b.code.toLowerCase().startsWith(normalized) ||
          b.city.toLowerCase().startsWith(normalized);
      if (aStarts != bStarts) {
        return aStarts ? -1 : 1;
      }
      final cityCompare = a.city.compareTo(b.city);
      if (cityCompare != 0) {
        return cityCompare;
      }
      return a.code.compareTo(b.code);
    });

    return results.take(8).toList();
  }

  static AirportOption? findBestMatch(String query, {String? excludeCode}) {
    final normalized = query.trim().toLowerCase();
    for (final airport in airports) {
      if (excludeCode != null && airport.code == excludeCode) {
        continue;
      }
      if (airport.code.toLowerCase() == normalized ||
          airport.shortLabel.toLowerCase() == normalized ||
          airport.fullLabel.toLowerCase() == normalized) {
        return airport;
      }
    }
    final matches = search(query, excludeCode: excludeCode);
    return matches.isEmpty ? null : matches.first;
  }
